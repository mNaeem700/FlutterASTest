// Thin wrapper around the FlutterASTest CLI: all analysis and test logic lives
// there, so the extension and the CLI always behave the same.
const vscode = require('vscode');
const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');

const KEY_VARIABLES = { gemini: 'GEMINI_API_KEY', openai: 'OPENAI_API_KEY' };
const WIDGET_CLASS =
  /class\s+(\w+)\s+extends\s+(?:StatelessWidget|StatefulWidget|GetView|GetWidget|HookWidget|StatefulHookWidget|ConsumerWidget|ConsumerStatefulWidget|HookConsumerWidget)\b/g;
const ANY_CLASS = /^\s*(?:abstract\s+)?class\s+([A-Z]\w*)/gm;
const STATE_CLASS = /extends\s+(?:\w*State)\s*</;
const INSTALL_HINT =
  'Install the FlutterASTest command with: dart pub global activate --source git https://github.com/mNaeem700/FlutterASTest';
const FAILING_HEADER = '// Generated by FlutterASTest. This test was failing when it was added; fix it before relying on it.';

let output;
let status;
let results;
let running = false;

function setting(name) {
  return vscode.workspace.getConfiguration('flutterastest').get(name);
}

function projectFolder() {
  const activeUri = vscode.window.activeTextEditor?.document.uri;
  const folder =
    (activeUri && vscode.workspace.getWorkspaceFolder(activeUri)) ||
    vscode.workspace.workspaceFolders?.[0];
  if (!folder) return undefined;
  return fs.existsSync(path.join(folder.uri.fsPath, 'pubspec.yaml')) ? folder.uri.fsPath : undefined;
}

function requireProject() {
  const project = projectFolder();
  if (!project) {
    vscode.window.showErrorMessage('FlutterASTest: open a Flutter project (a folder with pubspec.yaml).');
  }
  return project;
}

// A Windows shell is needed to start the pub `.bat` launcher, so every argument
// is quoted; project paths often contain spaces.
function quote(argument) {
  return `"${String(argument).replace(/"/g, '\\"')}"`;
}

function startCli(args, options) {
  return spawn([quote(setting('executable')), ...args.map(quote)].join(' '), { shell: true, ...options });
}

function looksLikeMissingCli(code, text) {
  return code !== 0 && /not recognized|not found|No such file/i.test(text) && !text.includes('FlutterASTest');
}

function showMissingCli() {
  output.appendLine(`\n${INSTALL_HINT}`);
  vscode.window.showErrorMessage(`FlutterASTest command not found. ${INSTALL_HINT}`);
}

async function apiKey(context, provider) {
  const name = `flutterastest.key.${provider}`;
  const saved = await context.secrets.get(name);
  if (saved) return saved;
  const entered = await vscode.window.showInputBox({
    prompt: `API key for ${provider} (kept in VS Code's secret storage)`,
    password: true,
    ignoreFocusOut: true,
  });
  if (entered) await context.secrets.store(name, entered);
  return entered;
}

function latestRun(project) {
  const runs = path.join(project, '.flutterastest', 'runs');
  if (!fs.existsSync(runs)) return undefined;
  return fs
    .readdirSync(runs)
    .map((run) => path.join(runs, run))
    .filter((dir) => fs.existsSync(path.join(dir, 'results.json')))
    .sort(
      (a, b) =>
        fs.statSync(path.join(b, 'results.json')).mtimeMs - fs.statSync(path.join(a, 'results.json')).mtimeMs,
    )[0];
}

function readResults(runDirectory) {
  try {
    return JSON.parse(fs.readFileSync(path.join(runDirectory, 'results.json'), 'utf8'));
  } catch {
    return undefined;
  }
}

async function openReport() {
  const project = projectFolder();
  const run = project && latestRun(project);
  if (!run) {
    vscode.window.showInformationMessage('FlutterASTest: no report yet. Generate tests first.');
    return;
  }
  await vscode.env.openExternal(vscode.Uri.file(path.join(run, 'report.html')));
}

// Asks before code first goes to a cloud provider, and remembers the answer.
async function cloudConsent(context, provider) {
  const name = `flutterastest.cloudConsent.${provider}`;
  if (context.globalState.get(name)) return true;
  const choice = await vscode.window.showWarningMessage(
    `The "${provider}" provider sends parts of your source code to a cloud service, under that service's terms. ` +
      'A local model keeps your code on this machine.',
    { modal: true },
    'Send to Cloud',
    'Choose Provider',
  );
  if (choice === 'Choose Provider') await selectProvider();
  if (choice !== 'Send to Cloud') return false;
  await context.globalState.update(name, true);
  return true;
}

async function selectProvider() {
  const items = [
    { label: 'local', description: 'Your code stays on this machine (needs Ollama or similar)' },
    { label: 'gemini', description: 'Google Gemini with your own key; code is sent to Google' },
    { label: 'openai', description: 'OpenAI-compatible service with your own key; code is sent to it' },
  ];
  const picked = await vscode.window.showQuickPick(items, { title: 'FlutterASTest AI provider' });
  if (!picked) return;
  await vscode.workspace
    .getConfiguration('flutterastest')
    .update('provider', picked.label, vscode.ConfigurationTarget.Global);
  updateStatus();
}

function updateStatus() {
  status.text = `$(beaker) FlutterASTest: ${setting('provider')}`;
  status.tooltip =
    setting('provider') === 'local'
      ? 'Your code stays on this machine. Click to change the AI provider.'
      : 'Code is sent to a cloud provider. Click to change the AI provider.';
  status.show();
}

// Paths of a screen's test: in the project when it passed, else in the run's reports.
function testFiles(project, runDirectory, screen, isUnit) {
  const installed = path.join(project, 'test', 'flutterastest', ...(isUnit ? ['unit'] : []), `${screen}_test.dart`);
  const reported = path.join(runDirectory, 'tests', `${screen}_test.dart`);
  return { installed, reported };
}

// The latest run's results, in the Testing panel.
class ResultsView {
  constructor() {
    this.changed = new vscode.EventEmitter();
    this.onDidChangeTreeData = this.changed.event;
  }

  refresh() {
    this.changed.fire();
  }

  getTreeItem(item) {
    return item;
  }

  getChildren() {
    const project = projectFolder();
    const runDirectory = project && latestRun(project);
    const data = runDirectory && readResults(runDirectory);
    if (!data) return [];
    const isUnit = data.meta?.kind === 'unit';
    return data.screens.map((screen) => {
      const run = screen.final;
      const passed = Boolean(run && run.compiled && !run.timedOut && run.failed === 0 && run.passed > 0);
      const coverage = run?.screenCoverage?.percent;
      const item = new vscode.TreeItem(screen.screen);
      item.iconPath = new vscode.ThemeIcon(passed ? 'pass' : 'error');
      item.description = passed
        ? `${run.passed} tests${coverage === undefined ? '' : `, ${coverage}% lines`}`
        : run?.reason ?? 'no test was generated';
      item.tooltip = `${screen.screenFile}\n${run?.reason ?? ''}`;
      const files = testFiles(project, runDirectory, screen.screen, isUnit);
      const file = passed && fs.existsSync(files.installed) ? files.installed : files.reported;
      item.contextValue = passed ? 'flutterastest.passed' : 'flutterastest.failed';
      item.testFiles = files;
      item.command = { command: 'vscode.open', title: 'Open Test', arguments: [vscode.Uri.file(file)] };
      return item;
    });
  }
}

// A failing test can still be a useful start, so the developer may keep it.
async function addToProject(item) {
  if (!item?.testFiles) return;
  const { installed, reported } = item.testFiles;
  if (!fs.existsSync(reported)) {
    vscode.window.showWarningMessage('FlutterASTest: this screen has no generated test file.');
    return;
  }
  if (fs.existsSync(installed)) {
    const choice = await vscode.window.showWarningMessage(
      `${path.basename(installed)} already exists. Replace it?`,
      { modal: true },
      'Replace',
    );
    if (choice !== 'Replace') return;
  }
  fs.mkdirSync(path.dirname(installed), { recursive: true });
  fs.writeFileSync(installed, `${FAILING_HEADER}\n${fs.readFileSync(reported, 'utf8')}`);
  await vscode.window.showTextDocument(vscode.Uri.file(installed));
}

// Runs in the output panel, not a terminal: the user's terminal may be
// PowerShell, cmd or bash, and each quotes a command differently.
function runDoctor() {
  const project = projectFolder();
  const args = ['doctor'];
  if (project) args.push(project);
  args.push('--provider', setting('provider'));
  const model = setting('model');
  if (model) args.push('--model', model);

  output.clear();
  output.show(false);
  return new Promise((resolve) => {
    let text = '';
    const append = (data) => {
      text += data.toString();
      output.append(data.toString());
    };
    const child = startCli(args, { cwd: project });
    child.stdout.on('data', append);
    child.stderr.on('data', append);
    child.on('close', (code) => {
      if (looksLikeMissingCli(code, text)) showMissingCli();
      resolve();
    });
  });
}

function summarize(project) {
  const runDirectory = latestRun(project);
  const data = runDirectory && readResults(runDirectory);
  if (!data) return undefined;
  const total = data.screens.length;
  const working = data.screens.filter((s) => s.final && s.final.compiled && s.final.failed === 0 && s.final.passed > 0).length;
  const firstFailure = data.screens.find((s) => s.final?.reason)?.final.reason;
  return { total, working, firstFailure, installed: (data.installedTests ?? []).length };
}

async function run(context, { names = [], promptsOnly = false, unit = false } = {}) {
  if (running) {
    vscode.window.showWarningMessage('FlutterASTest is already running.');
    return;
  }
  const project = requireProject();
  if (!project) return;

  const provider = setting('provider');
  const args = [unit ? 'unit' : 'generate', project, '--provider', provider];
  const model = setting('model');
  if (model) args.push('--model', model);
  if (provider === 'local' && !model && !promptsOnly) {
    const choice = await vscode.window.showErrorMessage(
      'Choose a local model first (see "ollama list"), or choose another AI provider.',
      'Open Settings',
      'Choose Provider',
    );
    if (choice === 'Open Settings') {
      await vscode.commands.executeCommand('workbench.action.openSettings', 'flutterastest.model');
    } else if (choice === 'Choose Provider') {
      await selectProvider();
    }
    return;
  }
  for (const name of names) args.push('--screen', name);
  if (promptsOnly) args.push('--prompts-only');
  else if (setting('reflect')) args.push('--reflect');
  const flutterPath = setting('flutterPath');
  if (flutterPath) args.push('--flutter', flutterPath);

  const env = { ...process.env };
  if (!promptsOnly && provider !== 'local') {
    if (!(await cloudConsent(context, provider))) return;
    const key = await apiKey(context, provider);
    if (!key) return;
    env[KEY_VARIABLES[provider]] = key;
    args.push('--accept-cloud');
  }

  running = true;
  output.clear();
  output.show(false);
  await vscode.window.withProgress(
    { location: vscode.ProgressLocation.Notification, title: 'FlutterASTest', cancellable: true },
    (progress, token) =>
      new Promise((resolve) => {
        let text = '';
        const append = (data) => {
          const chunk = data.toString();
          text += chunk;
          output.append(chunk);
          const line = chunk.trim().split(/\r?\n/).pop();
          if (line) progress.report({ message: line.slice(0, 90) });
        };
        progress.report({ message: 'starting...' });
        const child = startCli(args, { cwd: project, env });
        token.onCancellationRequested(() => child.kill());
        child.stdout.on('data', append);
        child.stderr.on('data', append);
        child.on('error', (error) => output.appendLine(`Could not start FlutterASTest: ${error.message}`));
        child.on('close', async (code) => {
          running = false;
          resolve();
          results.refresh();
          if (looksLikeMissingCli(code, text)) {
            showMissingCli();
            return;
          }
          if (code !== 0) {
            vscode.window.showErrorMessage('FlutterASTest stopped with an error. See the output panel for why.');
            return;
          }
          if (promptsOnly) {
            vscode.window.showInformationMessage('FlutterASTest: prompts are ready in .flutterastest/.');
            return;
          }
          const summary = summarize(project);
          if (!summary) return;
          const message = `FlutterASTest: ${summary.working} of ${summary.total} have working tests.`;
          const choice =
            summary.working === summary.total
              ? await vscode.window.showInformationMessage(`${message} They are in test/flutterastest/.`, 'Open Report')
              : await vscode.window.showWarningMessage(
                  `${message} ${summary.firstFailure ?? 'See the output panel for why.'}`,
                  'Open Report',
                  'Show Results',
                );
          if (choice === 'Open Report') await openReport();
          if (choice === 'Show Results') await vscode.commands.executeCommand('flutterastest.results.focus');
        });
      }),
  );
}

// Lists what can be tested and lets the developer choose.
async function pickTargets(context, unit) {
  const project = requireProject();
  if (!project) return;
  const targets = await vscode.window.withProgress(
    { location: vscode.ProgressLocation.Notification, title: 'FlutterASTest: reading your project...' },
    () =>
      new Promise((resolve) => {
        let stdout = '';
        let stderr = '';
        const args = ['targets', project];
        if (unit) args.push('--kind', 'unit');
        const child = startCli(args, { cwd: project });
        child.stdout.on('data', (d) => (stdout += d.toString()));
        child.stderr.on('data', (d) => (stderr += d.toString()));
        child.on('close', (code) => {
          try {
            resolve(JSON.parse(stdout.trim().split(/\r?\n/).pop()));
          } catch {
            output.append(stdout + stderr);
            output.show(false);
            if (looksLikeMissingCli(code, stdout + stderr)) showMissingCli();
            else vscode.window.showErrorMessage('FlutterASTest could not read the project. See the output panel.');
            resolve(undefined);
          }
        });
      }),
  );
  if (!targets) return;
  if (targets.length === 0) {
    vscode.window.showInformationMessage(`FlutterASTest: no ${unit ? 'classes' : 'screens'} found in this project.`);
    return;
  }
  const picked = await vscode.window.showQuickPick(
    targets.map((t) => ({ label: t.name, description: t.file })),
    { canPickMany: true, title: `Choose ${unit ? 'classes' : 'screens'} to test`, matchOnDescription: true },
  );
  if (picked?.length) await run(context, { names: picked.map((p) => p.label), unit });
}

function namesInActiveFile(unit) {
  const editor = vscode.window.activeTextEditor;
  if (!editor || editor.document.languageId !== 'dart') return [];
  const text = editor.document.getText();
  const widgets = [...text.matchAll(WIDGET_CLASS)].map((match) => match[1]);
  if (!unit) return widgets;
  return [...text.matchAll(ANY_CLASS)]
    .filter((match) => !widgets.includes(match[1]))
    .filter((match) => !STATE_CLASS.test(text.slice(match.index, match.index + 200).split('{')[0]))
    .map((match) => match[1]);
}

function runForFile(context, unit) {
  const names = namesInActiveFile(unit);
  if (names.length === 0) {
    vscode.window.showInformationMessage(
      `FlutterASTest: no ${unit ? 'classes' : 'widget screens'} in this file. Open a Dart file that has one.`,
    );
    return undefined;
  }
  return run(context, { names, unit });
}

function activate(context) {
  output = vscode.window.createOutputChannel('FlutterASTest');
  status = vscode.window.createStatusBarItem(vscode.StatusBarAlignment.Left);
  status.command = 'flutterastest.selectProvider';
  results = new ResultsView();
  updateStatus();
  const register = (id, handler) => vscode.commands.registerCommand(id, handler);
  context.subscriptions.push(
    output,
    status,
    vscode.window.registerTreeDataProvider('flutterastest.results', results),
    register('flutterastest.generateProject', () => run(context)),
    register('flutterastest.generateFile', () => runForFile(context, false)),
    register('flutterastest.pickScreens', () => pickTargets(context, false)),
    register('flutterastest.unitProject', () => run(context, { unit: true })),
    register('flutterastest.unitFile', () => runForFile(context, true)),
    register('flutterastest.pickClasses', () => pickTargets(context, true)),
    register('flutterastest.preview', () => run(context, { promptsOnly: true })),
    register('flutterastest.openReport', openReport),
    register('flutterastest.addToProject', addToProject),
    register('flutterastest.selectProvider', selectProvider),
    register('flutterastest.doctor', runDoctor),
    register('flutterastest.refreshResults', () => results.refresh()),
    register('flutterastest.setApiKey', async () => {
      const provider = setting('provider');
      await context.secrets.delete(`flutterastest.key.${provider}`);
      await apiKey(context, provider);
    }),
    vscode.workspace.onDidChangeConfiguration((event) => {
      if (event.affectsConfiguration('flutterastest.provider')) updateStatus();
    }),
  );
  if (!context.globalState.get('flutterastest.welcomed')) {
    context.globalState.update('flutterastest.welcomed', true);
    vscode.commands.executeCommand(
      'workbench.action.openWalkthrough',
      'NeemiiDevs.flutterastest#flutterastest.start',
    );
  }
}

function deactivate() {}

module.exports = { activate, deactivate };
