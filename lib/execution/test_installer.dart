import 'dart:io';

import 'package:path/path.dart' as p;

import '../experiment/models/screen_outcome.dart';

/// Puts finished tests into the developer's project at `test/flutterastest/`.
///
/// Only files whose tests all passed, without ignoring errors, are installed, so a generation never
/// turns the developer's test suite red; the others stay in the run's reports.
/// A file without [marker] is the developer's own and is never overwritten.
class TestInstaller {
  const TestInstaller();

  static const directoryName = 'flutterastest';
  static const marker = '// Generated by FlutterASTest. Regenerating overwrites this file.';

  /// Returns the installed paths, relative to the project.
  List<String> install(String projectPath, List<ScreenOutcome> outcomes, {bool unit = false}) {
    final directory = Directory(p.joinAll([projectPath, 'test', directoryName, if (unit) 'unit']));
    final installed = <String>[];

    for (final outcome in outcomes) {
      final best = outcome.best;
      if (best == null || !best.honestlyPassed) continue;
      directory.createSync(recursive: true);
      final file = _target(directory.path, outcome.screenName);
      file.writeAsStringSync('$marker\n${best.code.trimRight()}\n');
      installed.add(p.relative(file.path, from: projectPath).replaceAll(r'\', '/'));
    }
    return installed;
  }

  static File _target(String directory, String screen) {
    var file = File(p.join(directory, '${screen}_test.dart'));
    for (var n = 2; file.existsSync() && !_isOurs(file); n++) {
      file = File(p.join(directory, '${screen}_generated${n}_test.dart'));
    }
    return file;
  }

  static bool _isOurs(File file) => file.readAsStringSync().startsWith(marker);
}
